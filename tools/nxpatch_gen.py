#!/usr/bin/env python3
"""
Deterministic NXPT (*.nxpatch) recipe generator for Switch NSO -> nx2android patched.bin.
Stores ZERO copyrighted Switch executable bytes: only header hashes, Build ID, layout
parameters, sparse instruction-rewrite diff hunks (relative to the LZ4-decompressed flat NSO),
and the appended trampoline/key-page tail generated by patch_nso.py.

Binary Format ("NXPT", version 1, little-endian):
  Header (144 bytes):
    0x00  4s   magic = b"NXPT"
    0x04  u32  version = 1
    0x08  u32  flags (bit 0 = FAR layout)
    0x0c  u32  num_hunks
    0x10  16s  build_id (16 bytes from NSO +0x40)
    0x20  32s  raw_nso_sha256
    0x40  32s  base_img_sha256 (flat decompressed NSO image before patching)
    0x60  32s  out_patched_sha256 (expected *.patched.bin SHA-256)
    0x80  u64  base_img_len (length of flat decompressed NSO image)
    0x88  u64  out_total_len (exact length of *.patched.bin)
    0x90  u64  tail_offset (byte offset where appended patch/trampoline area begins; <= out_total_len)
    0x98  u64  tail_len (out_total_len - tail_offset)
  Hunks (num_hunks entries):
    u32 offset (in base_img, < base_img_len)
    u32 length
    u8[length] new_bytes (rewritten ARM64 instructions / sdk_patches cuts)
  Tail (tail_len bytes):
    u8[tail_len] appended patch/trampoline/key-page region
"""
import hashlib, os, struct, sys
import lz4.block

def build_base_image(raw_nso: bytes, far: bool) -> tuple[bytes, bytes]:
    assert raw_nso[:4] == b'NSO0', 'Not an NSO0 file'
    flags = struct.unpack_from('<I', raw_nso, 0x0C)[0]
    segs = [struct.unpack_from('<III', raw_nso, 0x10 + i * 0x10) for i in range(3)]
    bss = struct.unpack_from('<I', raw_nso, 0x3C)[0]
    csz = [struct.unpack_from('<I', raw_nso, 0x60 + i * 4)[0] for i in range(3)]
    build_id = raw_nso[0x40:0x50]

    img = bytearray(segs[2][1] + segs[2][2] + (0 if far else bss))
    for i, (fo, mo, sz) in enumerate(segs):
        chunk = raw_nso[fo:fo + csz[i]]
        if (flags >> i) & 1:
            chunk = lz4.block.decompress(chunk, uncompressed_size=sz)
        img[mo:mo + sz] = chunk
    return bytes(img), build_id

def diff_hunks(base: bytes, patched_prefix: bytes) -> list[tuple[int, bytes]]:
    assert len(base) == len(patched_prefix)
    hunks = []
    n = len(base)
    i = 0
    # Scan word-aligned or byte-by-byte efficiently in 4KB blocks to skip identical regions fast
    BLK = 4096
    while i < n:
        end = min(i + BLK, n)
        if base[i:end] == patched_prefix[i:end]:
            i = end
            continue
        # Fine scan within differing block
        j = i
        while j < end:
            if base[j] != patched_prefix[j]:
                start = j
                while j < n and base[j] != patched_prefix[j]:
                    j += 1
                # Merge tiny gaps <= 8 bytes to keep hunk table compact
                while hunks and start - (hunks[-1][0] + len(hunks[-1][1])) <= 8:
                    prev_off, prev_data = hunks.pop()
                    start = prev_off
                hunks.append((start, patched_prefix[start:j]))
                if j > end:
                    end = j
            else:
                j += 1
        i = end
    return hunks

def generate(raw_nso_path: str, patched_bin_path: str, fixups_tsv_path: str, out_nxpatch_path: str):
    raw_nso = open(raw_nso_path, 'rb').read()
    patched = open(patched_bin_path, 'rb').read()
    fixups_txt = open(fixups_tsv_path, 'r', encoding='utf-8').read()
    far = '# FILE_IMAGE_LEN\t' in fixups_txt
    # Find tail_offset: after base_img (padded zeros between base_img_len and tail_offset are implicit 0s)
    base_img, build_id = build_base_image(raw_nso, far)
    base_len = len(base_img)
    assert len(patched) >= base_len, f'patched.bin shorter than base_img: {len(patched)} < {base_len}'

    hunks = diff_hunks(base_img, patched[:base_len])
    # Skip leading zero padding after base_len to find first non-zero tail byte (saves megabytes of zero padding!)
    tail_off = base_len
    n_pat = len(patched)
    while tail_off < n_pat and patched[tail_off] == 0:
        tail_off += 1
    tail = patched[tail_off:]

    raw_sha = hashlib.sha256(raw_nso).digest()
    base_sha = hashlib.sha256(base_img).digest()
    out_sha = hashlib.sha256(patched).digest()

    hdr = struct.pack(
        '<4sIII16s32s32s32sQQQQ',
        b'NXPT', 1, 1 if far else 0, len(hunks),
        build_id, raw_sha, base_sha, out_sha,
        base_len, n_pat, tail_off, len(tail)
    )
    assert len(hdr) == 160
    os.makedirs(os.path.dirname(os.path.abspath(out_nxpatch_path)), exist_ok=True)
    with open(out_nxpatch_path, 'wb') as f:
        f.write(hdr)
        for off, data in hunks:
            f.write(struct.pack('<II', off, len(data)))
            f.write(data)
        f.write(tail)

    hunk_bytes = sum(len(d) for _, d in hunks)
    print(f'[nxpatch] {os.path.basename(out_nxpatch_path)}: build_id={build_id.hex()} far={int(far)} '
          f'hunks={len(hunks)} ({hunk_bytes} B) tail={len(tail)} B total_patch={os.path.getsize(out_nxpatch_path)} B '
          f'-> out_len={n_pat} sha256={out_sha.hex()}')

if __name__ == '__main__':
    if len(sys.argv) != 5:
        print('usage: nxpatch_gen.py <raw_nso> <patched.bin> <fixups.tsv> <out.nxpatch>', file=sys.stderr)
        sys.exit(2)
    generate(sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4])
